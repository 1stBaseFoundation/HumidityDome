"""Daily rollup, LLM summary, and email."""
from __future__ import annotations

import html
import re
import sqlite3
import time
from datetime import UTC, datetime, timedelta
from typing import Any

from . import llm, mail, store
from .config import Config


def local_now(cfg: Config, now: float | None = None) -> datetime:
    now = time.time() if now is None else now
    utc = datetime.fromtimestamp(now, tz=UTC).replace(microsecond=0)
    return utc + timedelta(hours=cfg.report.utc_offset_hours)


def local_date(cfg: Config, now: float | None = None) -> str:
    return local_now(cfg, now).date().isoformat()


def is_report_time(cfg: Config, now: float | None = None) -> bool:
    local = local_now(cfg, now)
    hour, minute = cfg.report.hour_minute
    return (local.hour, local.minute) >= (hour, minute)


def _inline_markdown(text: str) -> str:
    escaped = html.escape(text)
    escaped = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", escaped)
    escaped = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"<em>\1</em>", escaped)
    return escaped


def markdown_to_html(text: str) -> str:
    """Convert the LLM's simple markdown to Outlook-friendly HTML."""
    parts: list[str] = []
    in_list = False

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            if in_list:
                parts.append("</ul>")
                in_list = False
            continue

        heading = re.fullmatch(r"\*\*(.+?)\*\*", line)
        if heading:
            if in_list:
                parts.append("</ul>")
                in_list = False
            parts.append(
                f'<h3 style="margin:18px 0 6px;font-size:15px;color:#1a1a1a">'
                f"{html.escape(heading.group(1))}</h3>"
            )
            continue

        if line.startswith(("*", "-")):
            if not in_list:
                parts.append('<ul style="margin:6px 0 12px;padding-left:22px">')
                in_list = True
            parts.append(f"<li>{_inline_markdown(line[1:].strip())}</li>")
            continue

        if in_list:
            parts.append("</ul>")
            in_list = False
        parts.append(f'<p style="margin:6px 0">{_inline_markdown(line)}</p>')

    if in_list:
        parts.append("</ul>")
    return "\n".join(parts)


def render_html(rollup: dict[str, Any], summary: str, model: str) -> str:
    fleet = rollup.get("fleet", {})
    rows = []
    for node in rollup.get("nodes", []):
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(node.get('node', '')))}</td>"
            f"<td>{html.escape(str(node.get('ip', '')))}</td>"
            f"<td>{html.escape(str(node.get('last_state', '')))}</td>"
            f"<td>{node.get('uptime_pct', '')}</td>"
            f"<td>{node.get('peers_avg', '')}</td>"
            f"<td>{html.escape(str(node.get('version', '')))}</td>"
            f"<td>{node.get('lat_avg_ms', '')}</td>"
            f"<td>{node.get('incidents', 0)}</td>"
            "</tr>"
        )

    notes = "".join(
        f"<li>{html.escape(str(note))}</li>" for note in fleet.get("notes", [])
    )
    notes_html = f"<h3>Notes</h3><ul>{notes}</ul>" if notes else ""

    window = rollup.get("window", {})
    return f"""<!doctype html>
<html><body style="font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;color:#1a1a1a">
<h2 style="margin-bottom:4px">HumidityDome — daily infrastructure report</h2>
<p style="color:#666;margin-top:0">{html.escape(str(window.get('start', '')))} → {html.escape(str(window.get('end', '')))}</p>
<div style="background:#f6f8fa;border:1px solid #e1e4e8;border-radius:8px;padding:14px 16px">{markdown_to_html(summary)}</div>
<h3>Fleet</h3>
<p>{fleet.get('nodes_currently_up', '?')}/{fleet.get('nodes_total', '?')} nodes up · {fleet.get('incidents', 0)} incidents</p>
<h3>Nodes</h3>
<table style="border-collapse:collapse;font-size:13px">
<thead><tr style="text-align:left;background:#f6f8fa">
<th>node</th><th>ip</th><th>state</th><th>uptime %</th><th>peers avg</th><th>version</th><th>latency ms</th><th>incidents</th>
</tr></thead>
<tbody>{''.join(rows)}</tbody></table>
{notes_html}
<hr><p style="color:#999;font-size:12px">Generated by HumidityDome · all figures computed from node telemetry; summary prose by {html.escape(model)}.</p>
</body></html>"""


async def build_and_send_report(
    conn: sqlite3.Connection,
    cfg: Config,
    now: float | None = None,
    kind: str = "scheduled",
) -> dict[str, Any]:
    """Compile the last 24 h, summarise it, and email it.

    ``kind`` is stored on the report row: ``scheduled`` for the automatic 09:00
    summary, ``manual`` for a forced ``POST /report``. Only scheduled reports
    count toward "already sent today".
    """
    now = time.time() if now is None else now
    since = now - 24 * 3600

    rollup = store.build_rollup(conn, since, now, cfg.nodes)
    try:
        summary = await llm.summarize(rollup, cfg)
    except llm.LLMError:
        summary = llm.fallback_summary(rollup)
    body = render_html(rollup, summary, cfg.llm.model)

    date = local_date(cfg, now)
    subject = f"HumidityDome daily report — {date}"

    await mail.send_email(cfg.report.to_email, subject, body, cfg)
    store.mark_report_sent(conn, date, summary, kind=kind)

    return {"date": date, "subject": subject, "summary": summary, "kind": kind}